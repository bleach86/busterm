"""Builds src/font.c: the IBM PC's character set (code page 437) as 8x8
glyphs for the X16's text mode, from Daniel Hepper's public-domain font8x8
(tools/font8x8/), which has Latin, box drawing, blocks and Greek. The few
CP437 symbols it lacks that BBS art uses are drawn here; the rest of
those stay blank.

    python3 tools/mkfont.py

font8x8 keeps a row's leftmost pixel in bit 0; VERA wants it in bit 7.
"""
