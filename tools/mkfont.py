def load():
    glyphs = {}
    for name, array, first in TABLES:
        text = open(os.path.join(HERE, "font8x8", name)).read()
        body = text[text.index(array):]
        rows = re.findall(r"\{\s*((?:0x[0-9A-Fa-f]{2}\s*,\s*){7}0x[0-9A-Fa-f]{2})\s*\}", body)
        for i, row in enumerate(rows):
            glyphs[first + i] = [int(x, 16) for x in row.split(",")]
    return glyphs


def flip(byte):
    return int("{:08b}".format(byte)[::-1], 2)


def drawn(rows):
    return [int(r.replace("#", "1").replace(".", "0"), 2) for r in rows]


def main():
    font8x8 = load()
    out, missing = [], []
    for code in range(256):
        ch = LOW[code] if code < 32 else "⌂" if code == 0x7F else bytes([code]).decode("cp437")
        if ch in DRAWN:
            rows = drawn(DRAWN[ch])
        elif code and ord(ch) in font8x8:
            rows = [flip(b) for b in font8x8[ord(ch)]]
        else:
            rows = [0] * 8
            if code:
                missing.append("%02X %s" % (code, ch))
        out.append((code, ch, rows))
    lines = [
        "/* Generated by tools/mkfont.py: code page 437 as 8x8 glyphs, from",
        " * Daniel Hepper's public-domain font8x8, with a few symbols drawn. */",
        "#include \"font.h\"",
        "",
        "const unsigned char font_cp437[256 * 8] = {",
    ]
    for code, ch, rows in out:
        name = "%02X" % code if code < 32 or code == 0x7F else ch
        lines.append("    %s, /* %02X %s */" % (", ".join("0x%02X" % r for r in rows), code, name))
    lines.append("};")
    open(OUT, "w", encoding="utf-8").write("\n".join(lines) + "\n")
    print("wrote", os.path.relpath(OUT), "; blank:", ", ".join(missing) or "none")


if __name__ == "__main__":
    main()
